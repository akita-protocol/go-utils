func mapCheck(od OddsMap) error {
	ok := detailCheck(od.Head)
	if !ok {
		return fmt.Errorf("head count not 100")
	}

	ok = detailCheck(od.Eyes)
	if !ok {
		return fmt.Errorf("eyes count not 100")
	}

	ok = detailCheck(od.Snout)
	if !ok {
		return fmt.Errorf("snout count not 100")
	}

	ok = detailCheck(od.Body)
	if !ok {
		return fmt.Errorf("body count not 100")
	}

	ok = detailCheck(od.Back)
	if !ok {
		return fmt.Errorf("back count not 100")
	}

	ok = detailCheck(od.Fur)
	if !ok {
		return fmt.Errorf("fur count not 100")
	}

	ok = detailCheck(od.FurPlus)
	if !ok {
		return fmt.Errorf("furplus count not 100")
	}

	ok = detailCheck(od.Background)
	if !ok {
		return fmt.Errorf("background count not 100")
	}

	ok = detailCheck(od.BackgroundPlus)
	if !ok {
		return fmt.Errorf("background plus count not 100")
	}

	return nil
}

func detailCheck[V GenTwoTraits](od OddsDetails[V]) bool {
	var total int
	for _, trait := range od {
		total += trait
	}
	return total == 100
}

func insideOutOddsMap[V GenTwoTraits](od OddsDetails[V]) []V {
	r := []V{}
	for trait, odds := range od {
		if odds > 0 {
			for x := 0; x < odds; x++ {
				r = append(r, trait)
			}
		}
	}
	return r
}
